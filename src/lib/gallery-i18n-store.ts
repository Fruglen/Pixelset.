/** Recognise a server message. Returns the key and captured values, or null for unknown text. */
export function matchServerMessage(msg: string): { key: StoreKey; vars: Record<string, string> } | null {
  const s = (msg || "").trim();
  for (const m of SERVER_MESSAGES) {
    const hit = s.match(m.re);
    if (!hit) continue;
    const vars: Record<string, string> = {};
    (m.vars ?? []).forEach((v, i) => (vars[v] = hit[i + 1]));
    return { key: m.key, vars };
  }
  return null;
}


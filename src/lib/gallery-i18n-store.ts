// the gallery translates them on display with matchServerMessage(), which
// recognises each known message (including ones with numbers or names in
// them) and maps it to a key below. Anything unrecognised is shown as sent.
// Names inside messages (list names, access group names, region names) are
// the photographer's or visitor's content and are passed through untouched.


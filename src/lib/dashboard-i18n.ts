export function dashboardDict(lang: string): Dict {
  return DICTS[normalizeDashLang(lang)];
}

export function navLabels(lang: string): Record<string, string> {
  const l = normalizeDashLang(lang);
  return l === "en" ? {} : NAV_LABELS[l];
}

/** Translator for the dashboard: t("key", { var: value }) with English as the fallback; nav(label) for sub-navigation labels. */
export function dashT(lang: string) {
  const l = normalizeDashLang(lang);
  const d = DICTS[l];
  const t = (key: DashKey, vars: Record<string, string | number> = {}): string =>
    (d[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
  const labels = navLabels(l);
  const nav = (label: string) => labels[label] ?? label;
  return { t, nav, lang: l, tag: DASHBOARD_LANGUAGES.find((x) => x.id === l)!.tag };
}

/**
 * The account's dashboard language. User.locale is "auto" | "en" | "es" | "pt";
 * "auto" follows the browser's Accept-Language (Spanish or Portuguese speakers
 * get their language, everyone else English).
 */
export function resolveDashLang(locale: string | null | undefined, acceptLanguage: string | null | undefined): DashLang {
  if (locale && locale !== "auto") return normalizeDashLang(locale);
  const prefs = (acceptLanguage || "")
    .split(",")
    .map((p) => {
      const [tag, q] = p.trim().split(";q=");
      return { base: tag.toLowerCase().split("-")[0], q: q ? Number(q) || 0 : 1 };
    })
    .filter((p) => p.base)
    .sort((a, b) => b.q - a.q);
  for (const p of prefs) {
    if (p.base === "en" || p.base === "es" || p.base === "pt") return p.base;
  }
  return "en";
}

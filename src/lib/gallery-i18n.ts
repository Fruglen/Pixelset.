// field picks the language of the PUBLIC gallery interface: navigation,
// buttons, dialogs, download steps, favorites, and the password,
// registration, pre-release and expiry pages. The photographer's own content
// (gallery name, set names, file names, comments, notes, banners) is never
// translated. Strings use {placeholders}; steps are arrays.

export const GALLERY_LANGUAGES = [
  { id: "en", label: "English", tag: "en" },
  { id: "es", label: "Spanish", tag: "es" },
  { id: "fr", label: "French", tag: "fr" },
  { id: "de", label: "German", tag: "de" },
  { id: "nl", label: "Dutch", tag: "nl" },
  { id: "zh-Hans", label: "Chinese (Simplified)", tag: "zh-Hans" },
  { id: "pt", label: "Portuguese", tag: "pt" },
  { id: "sv", label: "Swedish", tag: "sv" },
] as const;

export type GalleryLang = (typeof GALLERY_LANGUAGES)[number]["id"];

/** Normalise a stored value ("zh" from older saves becomes zh-Hans). */
export function normalizeLang(v: string | null | undefined): GalleryLang {
  if (v === "zh" || v === "zh-CN" || v === "zh-Hans") return "zh-Hans";
  return (GALLERY_LANGUAGES.find((l) => l.id === v)?.id ?? "en") as GalleryLang;
}

